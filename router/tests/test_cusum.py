class Loss(unittest.TestCase):
    def fired(self,name):return LOSS[name]['fired']

    def test_replays_every_shared_case(self):
        for case in CASES['loss']:
            c=cusum.LossCusum();fired=[]
            for i,(lost,target) in enumerate(case['beats']):
                if c.feed(lost==1,target):fired.append(i)
            self.assertEqual(fired,case['fired'],case['name'])
            self.assertEqual((c.fired,c.gated),(case['count'],case['gated']),case['name'])

    def test_meaning_of_the_named_cases(self):
        self.assertEqual(self.fired('nothing lost'),[])
        self.assertEqual(self.fired('two lost in a row stay below H'),[])
        self.assertEqual(self.fired('a blackout of any length never reaches H'),[])
        self.assertEqual(self.fired('all refused never reaches H'),[])
        self.assertEqual(self.fired('three of five lost fires'),[5])
        self.assertEqual(self.fired('every second echo lost (one target only): gated'),[])
        self.assertGreater(LOSS['every second echo lost (one target only): gated']['gated'],5)
        self.assertTrue(self.fired('every second echo lost, then the other target too'))
        self.assertEqual(self.fired('lost with no target passes the gate'),[5])
        self.assertEqual(len(self.fired('a fire restarts the sum')),2)
        self.assertEqual(self.fired('sparse loss decays between losses'),[])
        self.assertEqual(self.fired('the other target lost exactly GATE beats ago is outside'),[])
        self.assertEqual(LOSS['the other target lost exactly GATE beats ago is outside']['gated'],1)
        self.assertEqual(self.fired('the other target lost GATE-1 beats ago is inside'),[10])

    def test_the_sum_never_goes_below_zero(self):
        for case in CASES['loss']:self.assertGreaterEqual(min(case['trace']),0.0,case['name'])

    def test_the_run_cap_counts_twice(self):
        c=cusum.LossCusum();c.feed(True);c.feed(True);before=c.s
        for _ in range(50):self.assertFalse(c.feed(True))
        self.assertEqual(c.s,before)

    def test_an_answer_ends_the_run(self):
        c=cusum.LossCusum();c.feed(True);c.feed(True);c.feed(False)
        self.assertTrue(c.feed(True,'a') is False or c.s==0.0)
        self.assertEqual(c.run,1)

    def test_a_gated_fire_restarts_the_sum(self):
        c=cusum.LossCusum()
        for i in range(6):
            fired=c.feed(i%2==0,'a')
            self.assertFalse(fired)
        self.assertEqual(c.gated,1);self.assertLess(c.s,cusum.H)

    def test_the_gate_window(self):
        c=cusum.LossCusum();c.feed(True,'b')
        for _ in range(cusum.GATE-3):c.feed(False,'a')
        c.feed(True,'a');c.feed(False,'a');c.feed(True,'a');self.assertEqual(c.fired+c.gated,0)
        c=cusum.LossCusum();c.feed(True,'b');c.feed(True,'a');c.feed(False,'a');self.assertTrue(c.feed(True,'a'),'inside the window')
        c=cusum.LossCusum();c.feed(True,'b')
        for _ in range(cusum.GATE-1):c.feed(False,'a')
        c.s=cusum.H-1.0
        self.assertFalse(c.feed(True,'a'),'exactly GATE beats ago is outside');self.assertEqual(c.gated,1)


def traces(seed,hours,share,blips=0.0,filtered=False):
    rng=random.Random(seed)
    beats=int(hours*3600);i=0
    while i<beats:
        if blips and rng.random()<blips/3600.0:
            for _ in range(min(15,1+int(rng.expovariate(1/5.0)))):
                yield True,'a' if i%2==0 else 'b'
                i+=1
        target='a' if i%2==0 else 'b'
        yield (rng.random()<share or (filtered and target=='b')),target
        i+=1


class FalseTriggers(unittest.TestCase):
    def fires(self,*args,**kw):
        c=cusum.LossCusum()
        return sum(1 for lost,target in traces(*args,**kw) if c.feed(lost,target))

    def test_healthy_clean_traces_never_fire(self):
        self.assertEqual(self.fires(1,240,0.002),0)

    def test_noisy_traces_stay_rare(self):
        # 240 h at the noisy assumption of the study: 1 % lost echoes, 4 blackouts per hour
        count=self.fires(2,240,0.01,blips=4.0)
        self.assertLessEqual(count/240.0,0.5,'at most one fire per two noisy hours')

    def test_single_blackouts_never_fire(self):
        # 4 blackouts per hour: only two of them a few seconds apart can fire (one fire per 24 h at most here)
        self.assertLessEqual(self.fires(3,240,0.0,blips=4.0),10)
        self.assertEqual(self.fires(3,240,0.0,blips=0.5),0)

    def test_every_echo_filtered_never_fires(self):
        self.assertEqual(self.fires(4,24,1.0),0)

    def test_one_filtered_target_stays_rare(self):
        self.assertLessEqual(self.fires(5,24,0.0,filtered=True),0)
        self.assertLessEqual(self.fires(6,24,0.002,filtered=True)/24.0,20)

    def test_persistent_real_loss_does_fire(self):
        self.assertGreater(self.fires(7,1,0.3),50)


class RttCases(unittest.TestCase):
    def test_replays_every_shared_case(self):
        for case in CASES['rtt']:
            w=cusum.RttWatch();runs=[]
            for rtt,target in case['beats']:
                s=w.feed(rtt,target)
                if runs and runs[-1][0]==s:runs[-1][1]+=1
                else:runs.append([s,1])
            self.assertEqual(runs,case['states'],case['name'])

    def states(self,name):return [s for s,_ in RTT[name]['states']]

    def test_flat_never_raises(self):
        self.assertEqual(RTT['flat']['raised'],0);self.assertEqual(self.states('flat'),['learning','ok'])

    def test_creep_raises(self):
        self.assertIn('congested',self.states('creep120'));self.assertIn('congested',self.states('creep600'))

    def test_a_pulse_clears_again(self):
        self.assertEqual(self.states('pulse')[-1],'ok');self.assertIn('congested',self.states('pulse'))

    def test_a_level_that_stays_is_learned(self):
        self.assertEqual(RTT['a level that stays is the new normal']['relearned'],1)

    def test_no_answers_stay_learning(self):
        self.assertTrue(RTT['no answers at all']['learning']);self.assertTrue(RTT['garbage values are no answers']['learning'])

    def test_a_target_without_a_base_is_skipped(self):
        w=cusum.RttWatch()
        for i in range(cusum.WARM):w.feed(30.0,'a' if i%40 else 'x')
        self.assertEqual(list(w.base),['a'])
        self.assertEqual(w.feed(3000.0,'x'),'ok');self.assertEqual(w.z,0.0)

    def test_the_two_targets_have_their_own_base(self):
        w=cusum.RttWatch()
        for i in range(cusum.WARM):w.feed(20.0 if i%2 else 200.0,'a' if i%2 else 'b')
        self.assertAlmostEqual(w.base['a'],math.log(20.0));self.assertAlmostEqual(w.base['b'],math.log(200.0))
        for i in range(600):self.assertEqual(w.feed(20.0 if i%2 else 200.0,'a' if i%2 else 'b'),'ok')

    def test_loss_alone_never_raises(self):
        rng=random.Random(9);w=cusum.RttWatch()
        for _ in range(3000):w.feed(None if rng.random()<0.4 else 50.0*math.exp(rng.gauss(0,0.25)),'a')
        self.assertEqual(w.raised,0)

    def test_noisy_hours_stay_rare(self):
        rng=random.Random(10);w=cusum.RttWatch()
        for _ in range(72*3600):
            rtt=60.0*math.exp(rng.gauss(0,0.35))
            if rng.random()<0.02:rtt*=rng.uniform(2,5)
            w.feed(rtt,'a')
        self.assertLessEqual(w.raised,3,'<= 1 per day')


class BoosterCases(unittest.TestCase):
    def play(self,name):return gen.play(BOOST[name]['steps'])

    def test_replays_every_shared_case(self):
        for case in CASES['booster']:self.assertEqual(gen.play(case['steps']),case['expected'],case['name'])

    def started(self,name):return [row['started'] for row in BOOST[name]['expected']]

    def test_the_gap_table(self):
        self.assertEqual([gap for _,gap in CASES['gaps']],[0,0,0,60,120,240,480,600,600,600,600,600])
        self.assertEqual([probe_policy.cusum_gap(clean) for clean in range(12)],[0,0,0,60,120,240,480,600,600,600,600,600])

    def test_the_rest_stops_an_ordinary_reason_not_the_cusum_reason(self):
        self.assertEqual(self.started('the rest stops an ordinary reason, not the CUSUM reason'),[True,None,None,False,True])

    def test_declines(self):
        self.assertEqual(self.started('a running episode declines everything'),[True,False,False])
        self.assertEqual(self.started('outside the watching states nothing starts'),[False,False])
        self.assertEqual(self.started('three failed checks: nothing to add')[-1],False)
        self.assertEqual(self.started('the decided failure model declines the CUSUM reason only'),[False,True])
        self.assertEqual(self.started('the undecided failure model does not decline'),[True])

    def test_clean_episodes_lengthen_the_gap(self):
        expected=BOOST['clean episodes lengthen the gap']['expected']
        starts=[row['started'] for row in expected if row['started'] is not None]
        # 3 free starts, then each gap refused one second early and started on time
        self.assertEqual(starts,[True,True,True]+[False,True]*6)
        self.assertEqual(expected[-1]['clean'],9)

    def test_a_failed_check_clears_the_count(self):
        expected=BOOST['a failed dense check clears the count']['expected']
        self.assertEqual(expected[-1]['started'],True,'after the failed check the next fire has no gap')
        self.assertEqual(expected[-2]['clean'],0)

    def test_another_reason_failed_check_clears_it_too(self):
        self.assertEqual(BOOST['an episode of another reason with a failed check clears it too']['expected'][-1]['started'],True)

    def test_a_clean_episode_of_another_reason_counts_nothing(self):
        self.assertEqual(BOOST['an episode of another reason ending clean counts nothing']['expected'][-1]['clean'],1)

    def test_a_clock_step_back_does_not_lock(self):
        self.assertTrue(BOOST['a wall clock stepped back does not lock the channel']['expected'][-1]['started'])

    def test_damaged_records_count_as_none(self):
        for name,case in BOOST.items():
            if name.startswith('a damaged record'):self.assertEqual(case['expected'][-1]['started'],True,name)

    def test_a_record_outside_the_pair_is_dropped(self):
        self.assertEqual(BOOST['a record of a channel outside the pair is dropped']['expected'][-1]['records'],1)

    def test_the_record_survives_the_end_of_a_boost(self):
        self.assertIn('cusum_at',probe_policy.CARRIED)

    def test_the_reason_is_a_suspicion_and_never_a_failure(self):
        self.assertIn(cusum.REASON,probe_policy.SUSPICION_REASONS);self.assertIn(cusum.REASON,probe_policy.REST_BYPASS)
        memory=gen.Memory();b=memory.b
        b.suspect(gen.SETTINGS,[{'profile':gen.SOURCE,'reason':cusum.REASON}],gen.PAIR,'OBSERVING',1000)
        self.assertNotIn('failures',b.state.get('streaks',{}).get(gen.SOURCE,{}),'no failure streak from a suspicion')


