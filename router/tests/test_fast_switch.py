class Wake(unittest.TestCase):
    def test_a_new_row_ends_one_nap(self):
        with tempfile.TemporaryDirectory() as root, patch.object(native,'RUNTIME',Path(root)), patch.object(native,'WAKE_SEEN',[None]):
            self.assertFalse(native.wake_due(),'no row')
            (Path(root)/C.WAKE_NAME).write_text('{"reason":"sample","time":5.5,"id":"a"}',encoding='utf-8')
            self.assertTrue(native.wake_due());self.assertFalse(native.wake_due(),'the same row wakes once')
            (Path(root)/C.WAKE_NAME).write_text('{"reason":"sample","time":6.5,"id":"a"}',encoding='utf-8')
            self.assertTrue(native.wake_due())
            for moment in (7.5,8.5):  # a heartbeat row is rewritten every beat, it wakes once per run of lost beats
                (Path(root)/C.WAKE_NAME).write_text('{"reason":"heartbeat","time":%s,"since":100.5,"id":"a"}'%moment,encoding='utf-8')
                self.assertEqual(native.wake_due(),moment==7.5)
            for bad in ('[]','{"time":"x"}','{','null'):
                (Path(root)/C.WAKE_NAME).write_text(bad,encoding='utf-8')
                self.assertFalse(native.wake_due(),bad)

    def test_the_nap_ends_early_and_only_then(self):
        with tempfile.TemporaryDirectory() as root, patch.object(native,'RUNTIME',Path(root)), patch.object(native,'WAKE_SEEN',[None]), patch.object(native,'STOP',False):
            (Path(root)/C.WAKE_NAME).write_text('{"reason":"sample","time":5.5,"id":"a"}',encoding='utf-8')
            sleeps=[]
            with patch.object(native.time,'sleep',lambda s:sleeps.append(s)):native.nap(2)
            self.assertEqual(sleeps,[],'the row ended the nap at once')


