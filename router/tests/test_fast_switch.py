        plain=self.run_fault(self.outage(40),model='hmm')
        self.assertLess(beat['switches'][0],plain['switches'][0]-5)
        self.assertEqual(beat['evidence'][0]['failure_rule'],'heartbeat');self.assertEqual(len(beat['rechecks']),1)
        wan=self.run_fault(self.outage(40),model='hmm',extra=options,beat=lost(False))
