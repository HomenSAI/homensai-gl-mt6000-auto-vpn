    def test_or_failures_leaves_earlier_and_keeps_every_guard(self):
        model=self.run_fault(self.outage(40),model='hmm')
        two=self.run_fault(self.outage(40),model='hmm',extra={'hmm_or_failures':2})
        three=self.run_fault(self.outage(40),model='hmm',extra={'hmm_or_failures':3})
