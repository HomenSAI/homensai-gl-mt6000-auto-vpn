class Recheck(Base):
    def selection(self):return {'source':dict(PROFILE),'target':{'id':G.RESERVE}}

    def status(self,points):
        agent.atomic_json(self.runtime/'status.json',{'samples':[G.sample(r) for r in points]})

    def backend(self,answer):
        calls=[];done=threading.Event()
        def recheck(identifier,seconds):
            calls.append((identifier,seconds));done.wait(5)
            if isinstance(answer,Exception):raise answer
            return answer
        return Mock(recheck=recheck),calls,done

    def test_the_probe_runs_beside_the_preparation(self):
        backend,calls,done=self.backend(True)
        running=pair.recheck_begin(backend,self.selection(),None,{'parallel_recheck':'1'})
        self.assertIsNotNone(running)
        for _ in range(500):
            if calls:break
            threading.Event().wait(0.01)
        self.assertEqual(calls,[(PROFILE['id'],pair.RECHECK_SECONDS)],'the probe started before the preparation ended')
        self.assertTrue(running[0].is_alive(),'and nothing waited for it')
        done.set()
        self.status([dict(G.BAD,t=990)])
        self.assertEqual(pair.late_recheck(backend,self.selection(),990,None,running),(pair.LATE_RECHECK_CODE,'probe'))
        self.assertEqual(len(calls),1,'its answer takes the place of a new probe')

    def started(self,answer):
        backend,calls,done=self.backend(answer)
        running=pair.recheck_begin(backend,self.selection(),None,{'parallel_recheck':'1'})  # the option is set here: the default may change
        self.assertIsNotNone(running)
        for _ in range(500):
            if calls:break
            threading.Event().wait(0.01)
        self.assertTrue(calls,'the probe started')
        return running,done

    def test_a_probe_that_answers_a_little_late_is_waited_for(self):
        running,done=self.started(True)
        self.status([dict(G.BAD,t=990)])
        timer=threading.Timer(0.3,done.set);timer.start();self.addCleanup(timer.cancel)
        with patch.object(pair,'RECHECK_WAIT',5):
            self.assertEqual(pair.late_recheck(None,self.selection(),990,None,running),(pair.LATE_RECHECK_CODE,'probe'),'the healthy answer that came within the wait stops the switch')

    def test_a_probe_that_never_answers_is_waited_for_only_that_long(self):
        running,done=self.started(True);self.addCleanup(done.set)
        self.status([dict(G.BAD,t=990)])
        began=time.monotonic()
        with patch.object(pair,'RECHECK_WAIT',0.3):
            result=pair.late_recheck(None,self.selection(),990,None,running)
        elapsed=time.monotonic()-began
        self.assertIsNone(result,'no answer in time: the switch goes on')
        self.assertGreaterEqual(elapsed,0.25,'it did wait')
        self.assertLess(elapsed,3,'and not longer than the bound')

    def test_a_false_or_failed_parallel_answer_goes_on(self):
        for answer in (False,None,RuntimeError('boom')):
            backend,calls,done=self.backend(answer);done.set()
            running=pair.recheck_begin(backend,self.selection(),None,{'parallel_recheck':'1'})
