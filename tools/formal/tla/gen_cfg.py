"""Writes the TLC .cfg files used by the CI cross-check (tools/formal/tla/tlc_check.py): one census cfg per (profile, fix set).

Copy of private/math/formal-tlc/gen_cfg.py reduced to the CI configurations (RUNS); the research set (alpha6, nofix, minus-Kx, trace
cfgs) stays in the private study. PY_ARGS must stay identical to ci_check.py PROFILES (a unit test compares them); the TLC constants
are derived from these arguments, so a cfg cannot say something else than its model.py run.

Fix sets: alpha6 (variant alpha6), nofix (variant fix, --fixed ''), allfix (K1T,K2,K3,K4,K5,K9,K11,K12,F32,T4A), minus-Kx (all but Kx).
Standard library only; run with  py -3 -I gen_cfg.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ALL = ['K1T', 'K2', 'K3', 'K4', 'K5', 'K9', 'K11', 'K12', 'F32', 'T4A']
PY_ARGS = {
    'held': ['--no-crash', '--no-power', '--no-expire'],
    'restart': ['--no-gl'],
    'faults': ['--no-gl', '--no-power', '--faults'],
    'faults-power': ['--no-gl', '--no-crash', '--faults'],
    'server': ['--no-gl', '--no-power', '--server'],
    'glpower-net': ['--no-crash', '--no-expire', '--ext', 'net'],
    'rebuild': ['--no-gl', '--no-power', '--rebuild'],
    'fast': ['--no-gl', '--no-power', '--fast-switch'],
    'fast-power': ['--no-gl', '--no-crash', '--fast-switch'],
    'window': ['--no-gl', '--no-crash', '--no-expire', '--window'],
    'keys': ['--no-gl', '--no-power', '--no-expire', '--key-pin', 'directional'],
}
# TLC configurations outside the CI gate, run by name (tlc_check.py --only NAME): keys-blocker is the code before the fix, kept to
# show what it removed, like --key-pin blocker in tools/tests of the model
MANUAL = {'keys-blocker': ['--no-gl', '--no-power', '--no-expire', '--key-pin', 'blocker']}
# profiles of ci_check.py on other branches whose option Supervisor.tla does not state yet; re-state the option, then move the profile
# to PY_ARGS. Any other profile without a cfg is red (tools/tests/test_tla_crosscheck.py).
NOT_RESTATED = {
    'prearm': '--prearm (feat/prearmed-reserve-20261104): the tick edge to FWD20, the steps FWD20 and FWD21',
    'prearm-power': '--prearm with a power cut',
    'prearm-gl': '--prearm with outside changes',
}


def tla_constants(args):
    """model.py arguments -> the constants of Supervisor.tla (the same order in every cfg)."""
    ext = args[args.index('--ext') + 1] if '--ext' in args else 'both'
    key_pin = args[args.index('--key-pin') + 1] if '--key-pin' in args else 'off'
    return dict(GL='--no-gl' not in args, Ext=ext, Crash='--no-crash' not in args, Power='--no-power' not in args,
                Expire='--no-expire' not in args, Faults='--faults' in args, Server='--server' in args,
                Rebuild='--rebuild' in args, Window='--window' in args, FastSwitch='--fast-switch' in args, KeyPin=key_pin)


ALL_ARGS = dict(PY_ARGS, **MANUAL)
PROFILES = {name: tla_constants(args) for name, args in ALL_ARGS.items()}
FIXSETS = {'alpha6': (False, []), 'nofix': (True, []), 'allfix': (True, ALL)}
for k in ALL:
    FIXSETS['minus-' + k] = (True, [x for x in ALL if x != k])
RUNS = [(name, 'allfix') for name in ALL_ARGS]   # model.py variant "fix" with every K fix on; the CI gate is every run outside MANUAL


def tla(v):
    if isinstance(v, bool):
        return 'TRUE' if v else 'FALSE'
    return '"%s"' % v


def constants(profile, fixset):
    fix, fixed = FIXSETS[fixset]
    lines = ['\\* generated by gen_cfg.py: profile %s, fix set %s' % (profile, fixset),
             '\\* model.py equivalent: py -3 model.py --variant %s %s %s' % (
                 'fix' if fix else 'alpha6', ('--fixed ' + ','.join(fixed)) if fix else '', ' '.join(ALL_ARGS[profile])),
             'SPECIFICATION Spec', 'CONSTANTS', '  Fix = %s' % tla(fix),
             '  Fixed = {%s}' % ', '.join('"%s"' % x for x in fixed)]
    lines += ['  %s = %s' % (k, tla(v)) for k, v in PROFILES[profile].items()]
    return lines


def render(profile, fixset):
    return '\n'.join(constants(profile, fixset) + ['INVARIANT TypeOK', 'INVARIANT Census']) + '\n'


def manifest_entries():
    out = []
    for profile, fixset in RUNS:
        fix, fixed = FIXSETS[fixset]
        out.append({'name': '%s-%s' % (profile, fixset), 'profile': profile, 'fixset': fixset, 'fixed': fixed, 'ci': profile not in MANUAL,
                    'py': ['--variant', 'fix' if fix else 'alpha6'] + (['--fixed', ','.join(fixed)] if fix else []) + ALL_ARGS[profile]})
    return out


def main():
    os.makedirs(os.path.join(HERE, 'cfg'), exist_ok=True)
    for e in manifest_entries():
        with open(os.path.join(HERE, 'cfg', e['name'] + '.cfg'), 'w', newline='\n') as f:
            f.write(render(e['profile'], e['fixset']))
    print('\n'.join(e['name'] for e in manifest_entries()))


if __name__ == '__main__':
    main()
